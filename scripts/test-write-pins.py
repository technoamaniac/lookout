#!/usr/bin/env python3
"""Checks how scripts/write-pins.py completes aapt2's platform checksums."""
import importlib.util
import pathlib
import unittest

spec = importlib.util.spec_from_file_location("write_pins", pathlib.Path(__file__).with_name("write-pins.py"))
write_pins = importlib.util.module_from_spec(spec)
spec.loader.exec_module(write_pins)


def artifact(name, sha256, origin="Generated by Gradle"):
    return (f'         <artifact name="{name}">\n'
            f'            <sha256 value="{sha256}" origin="{origin}"/>\n'
            f'         </artifact>\n')


def aapt2(version, *artifacts):
    return (f'      <component group="com.android.tools.build" name="aapt2" version="{version}">\n'
            + "".join(artifacts) + '      </component>\n')


OTHER = ('      <component group="com.android.tools.build" name="aapt2-proto" version="9.6.0-1">\n'
         + artifact("aapt2-proto-9.6.0-1.jar", "e" * 64) + '      </component>\n')


def fake_fetch(version, name):
    return {"linux": "1", "osx": "2", "windows": "3"}[name.rsplit("-", 1)[1].removesuffix(".jar")] * 64


class AddAapt2PlatformsTest(unittest.TestCase):

    def test_adds_missing_platforms_in_name_order(self):
        written = aapt2("9.6.0-1", artifact("aapt2-9.6.0-1-osx.jar", "a" * 64), artifact("aapt2-9.6.0-1.pom", "b" * 64))

        self.assertEqual(
            aapt2("9.6.0-1",
                  artifact("aapt2-9.6.0-1-linux.jar", "1" * 64, write_pins.PUBLISHED_ORIGIN),
                  artifact("aapt2-9.6.0-1-osx.jar", "a" * 64),
                  artifact("aapt2-9.6.0-1-windows.jar", "3" * 64, write_pins.PUBLISHED_ORIGIN),
                  artifact("aapt2-9.6.0-1.pom", "b" * 64)),
            write_pins.add_aapt2_platforms(written, fake_fetch))

    def test_leaves_a_complete_version_and_other_components_alone(self):
        complete = aapt2("9.5.1-1", *(artifact(f"aapt2-9.5.1-1-{platform}.jar", "c" * 64)
                                      for platform in write_pins.AAPT2_PLATFORMS))
        metadata = complete + OTHER

        def fail(version, name):
            raise AssertionError(f"fetched {name}")

        self.assertEqual(metadata, write_pins.add_aapt2_platforms(metadata, fail))

    def test_rejects_metadata_without_an_aapt2_component(self):
        with self.assertRaises(ValueError):
            write_pins.add_aapt2_platforms(OTHER, fake_fetch)


class ParsePublishedSha256Test(unittest.TestCase):

    def test_reads_the_checksum_before_an_optional_file_name(self):
        self.assertEqual("ab" * 32, write_pins.parse_published_sha256("x.jar", "AB" * 32 + "  x.jar\n"))

    def test_rejects_a_file_that_holds_no_sha256(self):
        for published in ["", "<html>Not Found</html>", "ab" * 31]:
            with self.subTest(published=published), self.assertRaises(ValueError):
                write_pins.parse_published_sha256("x.jar", published)


if __name__ == "__main__":
    unittest.main()
